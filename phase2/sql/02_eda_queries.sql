-- =====================================================================
-- Phase 1 — Business/EDA Queries (Standard ANSI SQL, runs on Snowflake & DuckDB)
-- =====================================================================

-- Q1. Monthly units sold trend, with promotion share
SELECT d.YEAR, d.MONTH,
       SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_DAILY_UNITS,
       ROUND(100.0 * AVG(CAST(f.PROMOTION_FLAG AS INT)), 2) AS PCT_ROWS_ON_PROMO
FROM FACT_SALES f JOIN DIM_DATE d ON f.DATE_KEY = d.DATE_KEY
GROUP BY d.YEAR, d.MONTH ORDER BY d.YEAR, d.MONTH;

-- Q2. Promotion lift: units sold on promo vs non-promo
SELECT f.PROMOTION_FLAG,
       COUNT(*) AS N_ROWS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS_SOLD,
       ROUND(AVG(f.PRICE_UNIT), 2) AS AVG_PRICE
FROM FACT_SALES f GROUP BY f.PROMOTION_FLAG;

-- Q3. Category performance
SELECT p.CATEGORY,
       SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS,
       ROUND(100.0 * AVG(CAST(f.PROMOTION_FLAG AS INT)), 2) AS PCT_ON_PROMO,
       ROUND(AVG(f.PRICE_UNIT), 2) AS AVG_PRICE
FROM FACT_SALES f JOIN DIM_PRODUCT p ON f.SKU = p.SKU
GROUP BY p.CATEGORY ORDER BY TOTAL_UNITS DESC;

-- Q4. Brand performance within category
SELECT p.CATEGORY, p.BRAND,
       SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS
FROM FACT_SALES f JOIN DIM_PRODUCT p ON f.SKU = p.SKU
GROUP BY p.CATEGORY, p.BRAND ORDER BY p.CATEGORY, TOTAL_UNITS DESC;

-- Q5. Region x Channel performance matrix
SELECT r.REGION, c.CHANNEL,
       SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS,
       ROUND(AVG(f.STOCK_AVAILABLE), 1) AS AVG_STOCK
FROM FACT_SALES f
JOIN DIM_REGION r ON f.REGION_KEY = r.REGION_KEY
JOIN DIM_CHANNEL c ON f.CHANNEL_KEY = c.CHANNEL_KEY
GROUP BY r.REGION, c.CHANNEL ORDER BY TOTAL_UNITS DESC;

-- Q6. Top/bottom SKUs by total units sold
SELECT p.SKU, p.BRAND, p.CATEGORY, SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS,
       MIN(f.DATE_KEY) AS FIRST_SALE_DATE
FROM FACT_SALES f JOIN DIM_PRODUCT p ON f.SKU = p.SKU
GROUP BY p.SKU, p.BRAND, p.CATEGORY
ORDER BY TOTAL_UNITS DESC;

-- Q7. Stockout proxy: rows with stock_available below the 10th percentile,
-- and their average units_sold vs the rest (does low stock constrain sales?)
WITH pct AS (
  SELECT PERCENTILE_CONT(0.1) WITHIN GROUP (ORDER BY STOCK_AVAILABLE) AS P10
  FROM FACT_SALES
)
SELECT CASE WHEN f.STOCK_AVAILABLE <= pct.P10 THEN 'Low Stock (<=P10)' ELSE 'Normal Stock' END AS STOCK_BAND,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS_SOLD,
       COUNT(*) AS N_ROWS
FROM FACT_SALES f CROSS JOIN pct
GROUP BY 1;

-- Q8. Day-of-week seasonality
SELECT d.DAY_OF_WEEK,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS,
       ROUND(100.0 * AVG(CAST(f.PROMOTION_FLAG AS INT)), 2) AS PCT_ON_PROMO
FROM FACT_SALES f JOIN DIM_DATE d ON f.DATE_KEY = d.DATE_KEY
GROUP BY d.DAY_OF_WEEK ORDER BY d.DAY_OF_WEEK;

-- Q9. Pack type performance
SELECT pt.PACK_TYPE,
       SUM(f.UNITS_SOLD) AS TOTAL_UNITS,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS,
       ROUND(AVG(f.PRICE_UNIT), 2) AS AVG_PRICE
FROM FACT_SALES f JOIN DIM_PACK_TYPE pt ON f.PACK_TYPE_KEY = pt.PACK_TYPE_KEY
GROUP BY pt.PACK_TYPE ORDER BY TOTAL_UNITS DESC;

-- Q10. Delivery lead time vs stock/units relationship
SELECT f.DELIVERY_DAYS,
       ROUND(AVG(f.STOCK_AVAILABLE), 1) AS AVG_STOCK,
       ROUND(AVG(f.UNITS_SOLD), 2) AS AVG_UNITS
FROM FACT_SALES f GROUP BY f.DELIVERY_DAYS ORDER BY f.DELIVERY_DAYS;

-- Q11. Year-over-year growth by category
WITH yearly AS (
  SELECT p.CATEGORY, d.YEAR, SUM(f.UNITS_SOLD) AS TOTAL_UNITS
  FROM FACT_SALES f JOIN DIM_PRODUCT p ON f.SKU = p.SKU JOIN DIM_DATE d ON f.DATE_KEY = d.DATE_KEY
  GROUP BY p.CATEGORY, d.YEAR
)
SELECT CATEGORY, YEAR, TOTAL_UNITS,
       ROUND(100.0 * (TOTAL_UNITS - LAG(TOTAL_UNITS) OVER (PARTITION BY CATEGORY ORDER BY YEAR))
             / LAG(TOTAL_UNITS) OVER (PARTITION BY CATEGORY ORDER BY YEAR), 2) AS YOY_GROWTH_PCT
FROM yearly ORDER BY CATEGORY, YEAR;
